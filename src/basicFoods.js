const norm = (s) => s.toLowerCase().replace(/ё/g, 'е');
const words = (s) => norm(s).split(/[^a-zа-я0-9,%]+/).filter(Boolean);

function commonPrefixLen(a, b) {
  let i = 0;
  while (i < a.length && i < b.length && a[i] === b[i]) i++;
  return i;
}

// «греча» ↔ «гречка», «вареные» ↔ «варёная»: общий префикс ≥ 4 или одно — начало другого
function tokenMatches(token, word) {
  return word.startsWith(token) || token.startsWith(word) || commonPrefixLen(token, word) >= 4;
}

// Продукт подходит, если каждое слово запроса находит себе слово в названии/алиасах
export function searchBasicFoods(query) {
  const tokens = words(query);
  if (!tokens.length) return [];
  return BASIC_FOODS.filter((f) => {
    const foodWords = [...words(f.name), ...f.aliases.flatMap(words)];
    return tokens.every((t) => foodWords.some((w) => tokenMatches(t, w)));
  }).map((f) => ({
    source: 'basic',
    name: f.name,
    brand: null,
    description: 'справочник',
    barcode: null,
    kcal100: f.kcal100,
    protein100: f.protein100,
    fat100: f.fat100,
    carbs100: f.carbs100,
  }));
}
